import type {
  AtlasPart,
  AtlasSystem,
  GeometryKind,
  SystemId,
  Vec3,
} from './types';

function part(
  id: string,
  name: string,
  fullName: string,
  geometry: GeometryKind,
  position: Vec3,
  size: Vec3,
  color: string,
  description: string,
  specifications: Record<string, string>,
  relatedComponents: string[],
  lesson: string,
  explodedPosition?: Vec3,
): AtlasPart {
  return {
    id,
    name,
    fullName,
    geometry,
    position,
    size,
    color,
    description,
    specifications,
    relatedComponents,
    lesson,
    category: 'Computer hardware',
    relatedTopics: Object.values(specifications).slice(0, 2),
    modelObjectName: id,
    cameraTarget: position,
    explodedPosition: explodedPosition ?? [
      position[0] * 1.65,
      position[1] * 1.5,
      position[2] + 1.1,
    ],
  };
}
